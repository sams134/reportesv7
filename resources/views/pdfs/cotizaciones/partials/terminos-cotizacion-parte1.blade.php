<h3>1. Alcance de la cotización</h3>
    <p>
        La presente cotización comprende únicamente los trabajos, materiales, pruebas, servicios y alcances
        expresamente descritos en el documento. Cualquier trabajo, repuesto, reparación, prueba, transporte,
        instalación, modificación o servicio adicional no indicado de forma expresa deberá ser cotizado y
        autorizado por separado.
    </p>
    <p>
        Cuando la cotización se emita con base en información preliminar, fotografías, datos de placa,
        inspección visual o descripción general del equipo, el alcance podrá ser ajustado si durante el desmontaje,
        inspección técnica, pruebas o proceso de reparación se identifican daños ocultos, condiciones anormales,
        componentes deteriorados o fallas que no hayan sido razonablemente detectables en la evaluación inicial.
    </p>

    <h3>2. Autorización para inicio de trabajos</h3>
    <p>
        CME no iniciará trabajos de reparación, fabricación, pruebas, suministro de repuestos, servicios externos
        o cualquier otro proceso productivo sin contar previamente con una orden de compra, autorización escrita
        o documento equivalente emitido por el cliente y aceptado por CME.
    </p>
    <p>
        La emisión de una orden de compra o autorización escrita implica aceptación del alcance, precios,
        condiciones comerciales, términos de pago, exclusiones, tiempos estimados de entrega y condiciones de
        garantía indicadas en la cotización.
    </p>

    <h3>3. Tiempo de entrega</h3>
    <p>
        El tiempo de entrega indicado en la cotización es estimado y podrá variar según disponibilidad de materiales,
        repuestos, servicios externos, carga de trabajo, resultados de pruebas, hallazgos durante el proceso de
        reparación, autorizaciones pendientes del cliente o situaciones fuera del control razonable de CME.
    </p>
    <p>
        Si durante la reparación se detecta una condición relevante que afecte el plazo originalmente estimado,
        CME notificará al cliente para informar la situación, el impacto técnico y, cuando corresponda, el nuevo
        tiempo estimado de entrega.
    </p>
    <p>
        Los tiempos de entrega quedarán suspendidos o modificados en caso de fuerza mayor, caso fortuito, crisis
        nacional, bloqueos, restricciones gubernamentales, disturbios, terremotos, inundaciones, incendios, fallas
        generalizadas de transporte, falta de energía, indisponibilidad de proveedores críticos u otros eventos
        externos que impidan o retrasen razonablemente la ejecución normal de los trabajos.
    </p>

    <h3>4. Trabajos adicionales y hallazgos durante pruebas</h3>
    <p>
        Durante el desmontaje, reparación, armado o pruebas finales del equipo, podrían detectarse defectos o fallas
        en componentes que no fueron posibles de evaluar preliminarmente. En esos casos, CME podrá informar al
        cliente y cotizar los trabajos, materiales o repuestos adicionales necesarios.
    </p>
    <p>
        Si durante las pruebas finales falla un componente cuya condición no podía determinarse razonablemente antes
        de la intervención, CME se reserva el derecho de agregar el costo correspondiente a la cotización, previa
        notificación y autorización del cliente cuando corresponda.
    </p>

    <h3>5. Diagnóstico y evaluación técnica</h3>
    <p>
        Cuando un equipo sea recibido para evaluación, diagnóstico, desmontaje, pruebas o inspección técnica, y
        posteriormente el cliente no autorice la reparación, CME podrá cobrar el diagnóstico, las pruebas realizadas,
        el desmontaje, la mano de obra, los insumos utilizados, los servicios externos y cualquier otro costo
        razonablemente incurrido para emitir el informe o determinar la condición del equipo.
    </p>
    <p>
        El retiro del equipo no reparado estará sujeto al pago previo de los cargos aplicables por diagnóstico,
        evaluación, desmontaje, pruebas, transporte, bodegaje u otros conceptos pendientes.
    </p>

    <h3>6. Garantía sobre trabajos realizados</h3>
    <p>
        La garantía de CME cubre únicamente los componentes, trabajos, servicios y materiales efectivamente
        intervenidos, reparados, rebobinados, sustituidos, ajustados o suministrados por CME, conforme al alcance
        aprobado en la cotización.
    </p>
    <p>
        En caso de que proceda una garantía, CME evaluará el equipo y, de confirmarse una falla atribuible directamente
        a los trabajos realizados por CME, asumirá la corrección correspondiente sobre los componentes intervenidos,
        dentro del plazo y condiciones de garantía indicados en la cotización.
    </p>
    <p>
        La garantía no cubre componentes no intervenidos, daños derivados de equipos externos, fallas de la máquina
        accionada, problemas de instalación, montaje, operación, alimentación eléctrica, control, protección,
        acoplamiento, lubricación, ambiente de trabajo o cualquier otra condición ajena al alcance ejecutado por CME.
    </p>

    <h3>7. Exclusiones de garantía</h3>
    <ul>
        <li>Fallas por alimentación eléctrica inadecuada del equipo.</li>
        <li>Desequilibrios extremos de voltaje, desfases, pérdida de fase o condiciones eléctricas anormales.</li>
        <li>Picos de voltaje, sobretensiones, transientes, descargas atmosféricas, fallas de variadores, arrancadores, protecciones o sistemas de control.</li>
        <li>Fallas en rodamientos por falta de lubricación, exceso de lubricación, lubricante inadecuado, contaminación, montaje incorrecto o condiciones externas de operación.</li>
        <li>Mala alineación, desbalance externo, vibración excesiva, base deficiente, acoplamiento incorrecto o montaje inadecuado.</li>
        <li>Golpes, maltratos, caídas, manipulación incorrecta o daños ocasionados durante transporte, almacenamiento, montaje o instalación por parte del cliente o terceros.</li>
        <li>Operación fuera de placa, sobrecarga, temperatura excesiva, ventilación deficiente, ambiente contaminado, humedad, químicos, polvo, abrasivos u otras condiciones severas no informadas o no corregidas.</li>
        <li>Apertura, desmontaje, modificación, reparación o intervención del equipo por personal ajeno a CME.</li>
        <li>Uso de repuestos, materiales o componentes suministrados por el cliente o por terceros, salvo que CME haya indicado expresamente lo contrario.</li>
        <li>Fallas en componentes no incluidos dentro del alcance de reparación aprobado.</li>
    </ul>

    <h3>8. Limitación de responsabilidad</h3>
    <p>
        La responsabilidad de CME, cuando corresponda, se limita exclusivamente a la corrección, reparación o sustitución
        de los trabajos o componentes intervenidos por CME, dentro del alcance aprobado y conforme a las condiciones
        de garantía aplicables.
    </p>
    <p>
        CME no será responsable por daños a otras unidades, equipos, procesos, instalaciones, máquinas accionadas,
        sistemas de control, producción, pérdidas económicas, lucro cesante, penalizaciones, pérdida de oportunidad,
        paros de planta, daños consecuenciales, indirectos o incidentales derivados directa o indirectamente del uso,
        instalación, operación o falla del equipo reparado.
    </p>