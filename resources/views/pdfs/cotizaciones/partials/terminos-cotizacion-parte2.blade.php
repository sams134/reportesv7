 <h3>9. Instalación, montaje y puesta en marcha</h3>
    <p>
        El cliente es responsable de verificar alineación, base, acople, protecciones eléctricas, parámetros de variador,
        lubricación, ventilación, sentido de giro y condiciones de carga antes de operar el equipo, salvo que dichos
        servicios hayan sido expresamente contratados a CME.
    </p>
    <p>
        Cualquier falla derivada de una puesta en marcha incorrecta, instalación deficiente, montaje inadecuado,
        lubricación incorrecta o conexión eléctrica inapropiada no estará cubierta por garantía.
    </p>

    <h3>10. Repuestos o materiales suministrados por el cliente</h3>
    <p>
        Cuando el cliente suministre materiales, repuestos o componentes para ser utilizados en la reparación, CME no
        garantiza la calidad, especificación, compatibilidad, desempeño o vida útil de dichos componentes. En estos casos,
        la garantía de CME, si aplica, se limitará únicamente a la mano de obra ejecutada directamente por CME.
    </p>

    <h3>11. Retiro de equipos reparados y bodegaje</h3>
    <p>
        Una vez informado al cliente que el equipo se encuentra reparado, terminado o listo para entrega, el cliente
        deberá retirarlo dentro de un plazo razonable.
    </p>
    <p>
        Si el equipo no es retirado dentro de los tres meses posteriores a la notificación de finalización, CME podrá
        cobrar bodegaje mensual equivalente al tres por ciento del valor cotizado, sin perjuicio de otros cargos
        pendientes que pudieran aplicar.
    </p>

    <h3>12. Equipos no autorizados o abandonados</h3>
    <p>
        Si un equipo evaluado, diagnosticado o cotizado no es autorizado para reparación y permanece en las instalaciones
        de CME por un período de un año sin ser retirado por el cliente, CME podrá considerarlo equipo abandonado.
    </p>
    <p>
        Previo a disponer del equipo, CME procurará notificar al cliente por los medios de contacto disponibles. Si el
        cliente no retira el equipo ni cancela los cargos pendientes dentro del plazo indicado en la notificación, CME
        podrá disponer del equipo, enviarlo a chatarra o gestionar su retiro según corresponda, en la medida permitida
        por la legislación aplicable.
    </p>

    <h3>13. Condiciones de pago</h3>
    <p>
        Los términos de pago serán los indicados en la cotización. CME podrá suspender el inicio, continuidad o entrega
        de trabajos si existen pagos vencidos, anticipos pendientes, falta de orden de compra, documentos incompletos o
        cualquier incumplimiento comercial por parte del cliente.
    </p>
    <p>
        La entrega del equipo podrá quedar condicionada a la cancelación total de los saldos pendientes, cargos por
        diagnóstico, trabajos adicionales, bodegaje, transporte, impuestos, servicios externos u otros conceptos aplicables.
    </p>

    <h3>14. Exclusiones generales de la cotización</h3>
    <p>
        Salvo que se indique expresamente lo contrario en la cotización, no se incluyen trabajos, materiales o servicios
        no detallados en el alcance. Esto puede incluir, entre otros: suministro de rodamientos, trabajos de torno,
        encamisados de tapaderas, metalizados de ejes, balanceo dinámico, transporte del equipo, instalación o montaje,
        grasa y lubricantes, sensores de temperatura, resistencias de calefacción, carbones de aterrizaje, repuestos
        especiales, servicios externos o pruebas adicionales.
    </p>

    <h3>15. Aceptación</h3>
    <p>
        La aprobación de la cotización, emisión de orden de compra, autorización escrita, entrega del equipo para
        reparación o instrucción de inicio de trabajos implica aceptación de estos términos y condiciones, salvo pacto
        escrito distinto aceptado por ambas partes.
    </p>
